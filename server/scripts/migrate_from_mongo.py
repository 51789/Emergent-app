"""One-off import of the legacy Emergent app data (JARVIS / CONNECTa, MongoDB) into PostgreSQL.

Only needed if the old database holds real users. It imports:
  * users       (bcrypt hashes are kept, so passwords keep working; role, plan, expiry)
  * push_tokens (only those whose user_id matches an imported user)
Legacy searches/results are NOT imported: the old results were generated by an LLM and are
not real listings. Users simply re-create their searches.

Usage (run `alembic upgrade head` first):
    pip install -r requirements-dev.txt          # provides pymongo
    python scripts/migrate_from_mongo.py \
        --mongo-url mongodb://localhost:27017 --mongo-db jarvis \
        --database-url postgresql+asyncpg://consulens:consulens@localhost:5432/consulens [--dry-run]
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pymongo import MongoClient  # noqa: E402
from sqlalchemy.dialects.postgresql import insert as pg_insert  # noqa: E402
from sqlalchemy.ext.asyncio import create_async_engine  # noqa: E402

from app.db.models import PushToken, User  # noqa: E402


def _aware(value: Any) -> datetime | None:
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=UTC)
    if isinstance(value, str) and value:
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            return None
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=UTC)
    return None


def _uuid(value: Any) -> uuid.UUID:
    try:
        return uuid.UUID(str(value))
    except ValueError:
        return uuid.uuid4()


def map_user(doc: dict[str, Any]) -> dict[str, Any] | None:
    email = (doc.get("email") or "").strip().lower()
    if not email:
        return None
    password_hash = doc.get("hashed_password") or None
    providers = []
    if password_hash:
        providers.append("password")
    if doc.get("auth_provider") == "google":
        providers.append("google")
    plan = doc.get("plan") if doc.get("plan") in ("free", "pro", "premium") else "free"
    now = datetime.now(UTC)
    return {
        "id": _uuid(doc.get("id")),
        "email": email,
        "name": (doc.get("name") or None),
        "password_hash": password_hash,
        "role": "admin" if doc.get("role") == "admin" else "user",
        "plan": plan,
        "plan_expires_at": _aware(doc.get("plan_expires_at")) if plan != "free" else None,
        "language": "it",
        "voice_gender": "female",
        "auth_providers": providers or ["password"],
        "created_at": _aware(doc.get("created_at")) or now,
        "updated_at": now,
    }


async def run(mongo_url: str, mongo_db: str, database_url: str, dry_run: bool) -> None:
    mongo = MongoClient(mongo_url)
    db = mongo[mongo_db]
    users = [u for u in (map_user(d) for d in db.users.find({}, {"_id": 0})) if u]
    user_ids = {u["id"] for u in users}
    tokens = []
    for doc in db.push_tokens.find({}, {"_id": 0}):
        uid = _uuid(doc.get("user_id"))
        token = doc.get("device_token")
        if uid in user_ids and token and doc.get("platform") in ("ios", "android", "web"):
            tokens.append(
                {"id": uuid.uuid4(), "user_id": uid, "token": token, "platform": doc["platform"]}
            )
    skipped = db.searches.count_documents({}), db.results.count_documents({})
    print(
        f"users: {len(users)}, push tokens: {len(tokens)}, "
        f"skipped legacy searches/results: {skipped[0]}/{skipped[1]}"
    )
    if dry_run:
        return

    engine = create_async_engine(database_url)
    async with engine.begin() as conn:
        if users:
            result = await conn.execute(
                pg_insert(User)
                .values(users)
                .on_conflict_do_nothing(index_elements=["email"])
                .returning(User.id)
            )
            inserted = {row[0] for row in result}
            print(f"inserted users: {len(inserted)} (existing emails skipped)")
            tokens = [t for t in tokens if t["user_id"] in inserted]
        if tokens:
            await conn.execute(
                pg_insert(PushToken).values(tokens).on_conflict_do_nothing(index_elements=["token"])
            )
            print(f"inserted push tokens: {len(tokens)}")
    await engine.dispose()
    mongo.close()


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--mongo-url", required=True)
    parser.add_argument("--mongo-db", required=True)
    parser.add_argument("--database-url", default=os.environ.get("DATABASE_URL"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if not args.database_url:
        parser.error("--database-url (or DATABASE_URL) is required")
    asyncio.run(run(args.mongo_url, args.mongo_db, args.database_url, args.dry_run))


if __name__ == "__main__":
    main()
